допустимые_категории={'специальные','биометрические','общедоступные','иные'}
допустимые_группы={'сотрудники','не_сотрудники'}
def проверить_данные(организация, системы, оборудование, каталог, сзи):
 ошибки=[]
 if not isinstance(организация,dict) or not организация.get('название'): ошибки.append('данные/организация.py: отсутствует название организации')
 if not isinstance(системы,list) or len(системы)<3: ошибки.append('данные/системы.py: требуется минимум три ИСПДн')
 номера=set()
 for s in системы:
  for поле in ('номер','название','категория_пдн','тип_субъектов','количество_субъектов','тип_угроз_по_условию','является_гис','фактические_меры','связанное_оборудование'):
   if поле not in s: ошибки.append(f"системы.py: система {s.get('номер','?')} — отсутствует поле {поле}")
  n=s.get('номер')
  if n in номера: ошибки.append(f'системы.py: повторяется номер {n}')
  номера.add(n)
  if s.get('категория_пдн') not in допустимые_категории: ошибки.append(f"системы.py: система {n} — недопустимая категория")
  if s.get('тип_субъектов') not in допустимые_группы: ошибки.append(f"системы.py: система {n} — недопустимая группа")
  if not isinstance(s.get('количество_субъектов'),int) or s.get('количество_субъектов',-1)<0: ошибки.append(f"системы.py: система {n} — количество должно быть целым неотрицательным")
  if s.get('тип_угроз_по_условию') not in (1,2,3): ошибки.append(f"системы.py: система {n} — тип угроз должен быть 1, 2 или 3")
 for e in оборудование:
  if not e.get('связанная_испдн'): ошибки.append(f"оборудование.py: {e.get('название')} — нет связи с ИСПДн")
 for m in каталог:
  if not all(k in m for k in ('код','название','группа','для_каких_уз','условие_применения','способ_проверки','источник')): ошибки.append('каталог_мер.py: неполная карточка меры')
 return ошибки
