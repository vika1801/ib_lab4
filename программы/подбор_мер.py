def подобрать_меры(система, уровень, каталог_мер):
 требуемые=[]; фактические=list(система.get('фактические_меры',[])); пробелы=[]
 for мера in каталог_мер:
  if уровень not in мера['для_каких_уз']: continue
  if мера['обязательность_или_условность']=='условная' and not мера.get('условие_применения'): continue
  карточка=dict(мера); карточка['причина_включения']=f"Мера применима к {уровень}: {мера['условие_применения']}"
  требуемые.append(карточка)
  if мера['код'] not in фактические: пробелы.append({'код':мера['код'],'название':мера['название'],'причина':'Не отмечена среди фактически реализованных мер','способ_подтверждения':мера['способ_проверки'],'источник':мера['источник']})
 проверка_гис={'рассмотрен':bool(система.get('является_гис')),'основание':'Приказ ФСТЭК №17 рассмотрен отдельно' if система.get('является_гис') else 'Система не является ГИС по исходным данным; применимость приказа №17 не отмечена'}
 return {'требуемые_меры':требуемые,'фактические_меры':фактические,'пробелы':пробелы,'проверка_гис':проверка_гис,'неприменимые_меры':[]}
