def проверить_оборудование(оборудование, системы):
 ids={s['номер'] for s in системы}; результаты=[]
 for e in оборудование:
  проблемы=[]
  связи=e.get('связанная_испдн',[])
  if not связи: проблемы.append('не указана связь с ИСПДн')
  for sid in связи:
   if sid not in ids: проблемы.append(f'ссылка на отсутствующую систему {sid}')
  if e.get('класс_по_учебной_схеме') not in ('ОТСС','ВТСС'): проблемы.append('не заполнена классификация ОТСС/ВТСС')
  if e.get('обрабатывает_пдн') and ('сетевое устройство' in e.get('тип','') or 'источник бесперебойного питания' in e.get('тип','')): проблемы.append('роль и признак обработки ПДн могут противоречить друг другу')
  if проблемы: результаты.append({'оборудование':e.get('название'),'системы':связи,'проблемы':проблемы,'рекомендация':'Уточнить связь, классификацию и назначение; документировать результат'})
 return результаты
