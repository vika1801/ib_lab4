from данные.матрица_уз import матрица_уз
ступени=['УЗ-4','УЗ-3','УЗ-2','УЗ-1']
def рассчитать_уз(категория, тип_субъектов, количество, тип_угроз):
 ошибки=[]
 if категория not in матрица_уз['базовые_уровни']: ошибки.append('категория отсутствует или неизвестна')
 if тип_субъектов not in ('сотрудники','не_сотрудники'): ошибки.append('группа субъектов должна быть сотрудники или не_сотрудники')
 if not isinstance(количество,int) or isinstance(количество,bool) or количество<0: ошибки.append('количество должно быть целым неотрицательным числом')
 if тип_угроз not in (1,2,3): ошибки.append('тип угроз должен быть 1, 2 или 3')
 параметры={'категория':категория,'тип_субъектов':тип_субъектов,'количество':количество,'тип_угроз':тип_угроз}
 if ошибки:return {'уровень':'недостаточно_данных','обоснование':'Расчёт не выполнен: '+ '; '.join(ошибки),'проверенные_параметры':параметры,'основание_матрицы':'не найдено','ошибки_ввода':ошибки}
 уровень=матрица_уз['базовые_уровни'][категория][тип_угроз]
 основание=f"базовое правило: категория={категория}, тип угроз={тип_угроз}"
 if тип_субъектов=='не_сотрудники' and количество>=матрица_уз['порог']:
  уровень=ступени[min(ступени.index(уровень)+1,len(ступени)-1)]
  основание+=f"; порог {матрица_уз['порог']} достигнут, уровень повышен на одну ступень строгости"
 объяснение=f"Категория «{категория}», субъектов: {тип_субъектов}, количество: {количество}, тип угроз: {тип_угроз}. {основание}."
 return {'уровень':уровень,'обоснование':объяснение,'проверенные_параметры':параметры,'основание_матрицы':основание,'ошибки_ввода':[]}
